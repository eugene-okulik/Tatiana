# Задание 1: Даны 2 числа a и b. Получить их сумму, разность и произведение.

# Ввод данных
a = float(input("Введите первое число (a): "))
b = float(input("Введите второе число (b): "))

# Вычисления
sum_ab = a + b
difference_ab = a - b
product_ab = a * b

# Вывод результатов
print(f"Сумма a и b: {sum_ab}")
print(f"Разность a и b: {difference_ab}")
print(f"Произведение a и b: {product_ab}")
   